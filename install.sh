#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# CySOC MISP integration for UTMStack v11 - installer
#
#   sudo ./install.sh                         install / upgrade (interactive checks)
#   sudo ./install.sh --url URL --api-key KEY install and write MISP settings
#   sudo ./install.sh --ensure                idempotent re-apply (used by cron after UTMStack updates)
#   sudo ./install.sh --test                  only test MISP connectivity from this host
#
# What it does
#   1. copies com.utmstack.misp.plugin to /utmstack/custom-plugins/
#   2. puts the plugin config in /utmstack/events-engine-workdir/pipeline/cysoc_misp.yaml
#   3. registers the plugin in the analysis order
#      (pipeline/zz_cysoc_misp_analysis_order.yaml, loaded after system_plugins_analysis.yaml)
#   4. bind-mounts the binary into the EventProcessor services at
#      /workdir/plugins/utmstack/com.utmstack.misp.plugin
#   5. installs a cron guard that re-applies 3-4 after a UTMStack update
# ---------------------------------------------------------------------------
set -euo pipefail

PLUGIN=com.utmstack.misp
BIN_NAME=${PLUGIN}.plugin
DATA_DIR=${UTMSTACK_DATA_DIR:-/utmstack}
WORKDIR=${DATA_DIR}/events-engine-workdir
PIPELINE=${WORKDIR}/pipeline
CUSTOM_DIR=${DATA_DIR}/custom-plugins
CONFIG=${PIPELINE}/cysoc_misp.yaml
ORDER_FILE=${PIPELINE}/zz_cysoc_misp_analysis_order.yaml
SYSTEM_ORDER=${PIPELINE}/system_plugins_analysis.yaml
TARGET=/workdir/plugins/utmstack/${BIN_NAME}
SERVICES=${UTMSTACK_EP_SERVICES:-"utmstack_event-processor-worker utmstack_event-processor-manager"}
CRON_FILE=/etc/cron.d/utmstack-misp-guard
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)

MODE=install
MISP_URL=""
MISP_KEY=""
FORCE=0

log()  { printf '[misp-install] %s\n' "$*"; }
warn() { printf '[misp-install] WARNING: %s\n' "$*" >&2; }
die()  { printf '[misp-install] ERROR: %s\n' "$*" >&2; exit 1; }

while [[ $# -gt 0 ]]; do
  case "$1" in
    --ensure)  MODE=ensure ;;
    --test)    MODE="test" ;;
    --url)     MISP_URL=${2:?}; shift ;;
    --api-key) MISP_KEY=${2:?}; shift ;;
    --force)   FORCE=1 ;;
    -h|--help) sed -n '2,20p' "$0"; exit 0 ;;
    *) die "unknown option $1" ;;
  esac
  shift
done

[[ $EUID -eq 0 ]] || die "run as root"

# ---- helpers ---------------------------------------------------------------

cfg_value() { # read a simple "key: value" from the plugin config
  grep -E "^[[:space:]]+$1:" "$CONFIG" 2>/dev/null | head -1 | sed -E "s/^[^:]+:[[:space:]]*//; s/[[:space:]]+#.*$//; s/^['\"]//; s/['\"]$//"
}

test_misp() {
  local url key insecure code
  url=$(cfg_value url); key=$(cfg_value apiKey); insecure=$(cfg_value insecureSkipVerify)
  [[ -n "$url" && -n "$key" && "$key" != "CHANGE_ME" ]] || { warn "url/apiKey not set in $CONFIG"; return 1; }
  local k=(); [[ "$insecure" == "true" ]] && k=(-k)
  log "testing MISP API at $url ..."
  code=$(curl -sS "${k[@]}" -o /tmp/misp-test.$$ -w '%{http_code}' --max-time 30 \
    -H "Authorization: $key" -H "Accept: application/json" -H "Content-Type: application/json" \
    -X POST "$url/attributes/restSearch" \
    -d '{"returnFormat":"json","to_ids":true,"published":true,"limit":5,"page":1}' ) || code=000
  if [[ "$code" == "200" ]]; then
    log "MISP OK (HTTP 200). Sample: $(grep -oE '"value": ?"[^"]*"' /tmp/misp-test.$$ | head -3 | tr '\n' ' ')"
    rm -f /tmp/misp-test.$$; return 0
  fi
  warn "MISP test failed (HTTP $code): $(head -c 300 /tmp/misp-test.$$ 2>/dev/null)"
  rm -f /tmp/misp-test.$$; return 1
}

pick_binary() {
  local arch
  case "$(uname -m)" in
    x86_64|amd64) arch=amd64 ;;
    aarch64|arm64) arch=arm64 ;;
    *) die "unsupported CPU architecture $(uname -m)" ;;
  esac
  if [[ -x "$HERE/bin/linux-$arch/$BIN_NAME" ]]; then
    echo "$HERE/bin/linux-$arch/$BIN_NAME"
  elif [[ -x "$HERE/plugin/$BIN_NAME" ]]; then
    echo "$HERE/plugin/$BIN_NAME"   # built locally with build.sh
  else
    die "no plugin binary found for linux-$arch (run ./build.sh)"
  fi
}

write_order_override() {
  # Rebuild the analysis order from UTMStack's own file every time, so plugins
  # UTMStack adds in future releases are kept, then append ours.
  [[ -f "$SYSTEM_ORDER" ]] || { warn "$SYSTEM_ORDER not found - is UTMStack v11 installed here?"; return 1; }
  local entries
  entries=$(awk '
    /^[[:space:]]*order:[[:space:]]*$/ {in_order=1; next}
    in_order && /^[[:space:]]*-[[:space:]]*/ {sub(/^[[:space:]]*-[[:space:]]*/, ""); gsub(/["\047]/, ""); print; next}
    in_order && NF {in_order=0}
  ' "$SYSTEM_ORDER" | grep -vx "$PLUGIN" || true)
  [[ -n "$entries" ]] || { warn "could not read the analysis order from $SYSTEM_ORDER"; return 1; }

  local tmp; tmp=$(mktemp)
  {
    echo "# Generated by CySOC MISP install.sh - do not edit; re-run install.sh --ensure."
    echo "# Loaded after system_plugins_analysis.yaml and overrides plugins.analysis.order."
    echo "plugins:"
    echo "  analysis:"
    echo "    order:"
    while IFS= read -r e; do echo "    - $e"; done <<<"$entries"
    echo "    - $PLUGIN"
  } >"$tmp"
  if ! cmp -s "$tmp" "$ORDER_FILE" 2>/dev/null; then
    install -m 0644 "$tmp" "$ORDER_FILE"
    log "analysis order updated: $(tr '\n' ' ' <<<"$entries")$PLUGIN"
  fi
  rm -f "$tmp"
}

service_has_mount() {
  docker service inspect "$1" --format '{{range .Spec.TaskTemplate.ContainerSpec.Mounts}}{{.Target}} {{end}}' 2>/dev/null \
    | tr ' ' '\n' | grep -qx "$TARGET"
}

ensure_mounts() {
  local svc
  for svc in $SERVICES; do
    if ! docker service inspect "$svc" >/dev/null 2>&1; then
      warn "service $svc not found (docker service ls | grep event-processor)"; continue
    fi
    if service_has_mount "$svc"; then
      [[ $MODE == ensure ]] || log "$svc already has the plugin mounted"
      continue
    fi
    log "mounting plugin into $svc (the service restarts, ~30-60 s of event-processing pause) ..."
    docker service update --detach=false --quiet \
      --mount-add "type=bind,source=${CUSTOM_DIR}/${BIN_NAME},target=${TARGET},readonly" "$svc" >/dev/null
  done
  return 0
}

install_cron() {
  # keep a copy next to the binary so the guard survives deleting this folder
  local self=${CUSTOM_DIR}/misp-install.sh
  if [[ "$(readlink -f "$0")" != "$self" ]]; then install -m 0755 "$0" "$self"; fi
  cat >"$CRON_FILE" <<EOF
# CySOC: re-apply the MISP plugin after UTMStack updates (docker stack deploy drops custom mounts)
*/10 * * * * root $self --ensure >>/var/log/utmstack-misp-guard.log 2>&1
EOF
  chmod 0644 "$CRON_FILE"
  log "cron guard installed: $CRON_FILE"
}

# ---- modes -------------------------------------------------------------------

if [[ $MODE == test ]]; then
  test_misp; exit $?
fi

if [[ $MODE == ensure ]]; then
  [[ -x "${CUSTOM_DIR}/${BIN_NAME}" && -f "$CONFIG" ]] || exit 0   # not installed: nothing to guard
  write_order_override || true
  ensure_mounts
  exit 0
fi

# full install
command -v docker >/dev/null || die "docker not found"
docker service ls >/dev/null 2>&1 || die "this must run on the UTMStack swarm manager node"
[[ -d "$PIPELINE" ]] || die "$PIPELINE not found (set UTMSTACK_DATA_DIR if UTMStack data is not in /utmstack)"

src=$(pick_binary)
install -d -m 0755 "$CUSTOM_DIR"
install -m 0755 "$src" "${CUSTOM_DIR}/${BIN_NAME}"
log "plugin binary installed: ${CUSTOM_DIR}/${BIN_NAME} ($(sha256sum "${CUSTOM_DIR}/${BIN_NAME}" | cut -c1-16)...)"

if [[ ! -f "$CONFIG" ]]; then
  install -m 0600 "$HERE/config/cysoc_misp.yaml" "$CONFIG"
  log "config created: $CONFIG"
else
  log "keeping existing config: $CONFIG"
fi
chmod 0600 "$CONFIG"
if [[ -n "$MISP_URL" ]]; then
  sed -i -E "s#^([[:space:]]+url:).*#\1 ${MISP_URL}#" "$CONFIG"
fi
if [[ -n "$MISP_KEY" ]]; then
  sed -i -E "s#^([[:space:]]+apiKey:).*#\1 ${MISP_KEY}#" "$CONFIG"
fi

if [[ "$(cfg_value apiKey)" == "CHANGE_ME" && $FORCE -eq 0 ]]; then
  warn "apiKey is still CHANGE_ME. Edit $CONFIG (or pass --url/--api-key) and run install.sh again."
  exit 2
fi

if ! test_misp && [[ $FORCE -eq 0 ]]; then
  die "MISP is not reachable with these settings. Fix $CONFIG, or re-run with --force to install anyway."
fi

write_order_override || die "cannot register the plugin in the analysis order"
ensure_mounts
install_cron

cat <<EOF

[misp-install] Done.
  Check status:  sudo $HERE/status.sh
  Config:        $CONFIG   (edits apply on the next refresh, no restart)
  Uninstall:     sudo $HERE/uninstall.sh
EOF
